import assert from 'node:assert/strict';
import {buildJourney,parseJourney,moveStop,reorderStop,dayIssues,schedule,dayDistance,dateFor,placesFor} from '../src/lib/travel/workbench';
const draft=buildJourney(['shanghai'],3,'2026-11-12');
assert.equal(draft.days.length,3);
assert.equal(dateFor(draft,2),'2026-11-14');
assert.equal(new Set(draft.days.flatMap(d=>d.stops.map(s=>s.placeId))).size,6);
assert(placesFor('shanghai').every(p=>p.point&&p.coordinateSource),'Every Shanghai reference has a map point and source');
assert.deepEqual(parseJourney(JSON.parse(JSON.stringify(draft))),draft);
assert.equal(parseJourney({...draft,start:'2026-02-30'}),null);
assert.equal(parseJourney({...draft,people:0}),null);
assert.equal(parseJourney({...draft,hotels:{shanghai:{name:'test',point:[Infinity,100]}}}),null);
assert.equal(parseJourney({...draft,days:[{...draft.days[0],stops:[{...draft.days[0].stops[0],placeId:'missing'}]}]}),null);
assert.throws(()=>buildJourney(['shanghai','beijing'],2));
assert.throws(()=>buildJourney(['shanghai'],3.5));
const stop=draft.days[0].stops[0];
const moved=moveStop(draft,'day-1',stop.id,'day-2');
assert.equal(moved.days[0].stops.length,1);assert.equal(moved.days[1].stops.length,3);
assert.equal(moved.days[1].stops.at(-1)?.id,stop.id);
const booked=structuredClone(draft);booked.days[0].stops[1].booking={time:'10:00',note:'User-held ticket'};
assert(dayIssues(booked.days[0],booked).some(i=>i.includes('overlaps')),'A fixed reservation must expose a schedule conflict');
assert.equal(schedule(booked.days[0],booked.pace)[1].start,600,'Never silently shift a booked entry time');
assert.deepEqual(moveStop(booked,'day-1',booked.days[0].stops[1].id,'day-2'),booked,'Booked stops cannot move to another day');
assert.deepEqual(reorderStop(booked,'day-1',stop.id,1),booked,'Flexible stops cannot exchange positions with booked stops');
const early=structuredClone(draft);early.days[0].stops[0].booking={time:'08:30',note:''};
assert.equal(schedule(early.days[0],early.pace)[0].conflict,false,'The first reservation can start earlier than the default day');
assert(dayDistance(draft.days[0],{point:[31.25,121.45]})>dayDistance(draft.days[0]),'Hotel pin contributes to the displayed connections');
const multi=buildJourney(['shanghai','beijing','xian'],10);assert.equal(multi.days.length,10);assert.equal(multi.days.filter(d=>d.transfer).length,2);
const other=multi.days.find(d=>d.city==='beijing'&&!d.transfer)!;
assert.deepEqual(moveStop(multi,multi.days[0].id,multi.days[0].stops[0].id,other.id),multi,'Cross-city stop moves are rejected');
console.log('PASS: day allocation, sourced map locations, hotel connections, locked bookings, overlap detection, cross-city guards, and validated draft restoration.');
